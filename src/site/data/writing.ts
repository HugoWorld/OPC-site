export const ARTICLES_PUBLISHED = ARTICLES.filter((a) => a.status === "published")

export function getArticle(category: string, slug: string) {
  return ARTICLES.find((a) => a.category === category && a.slug === slug)
}

export function getRelatedArticles(article: Article, count = 2) {
  return ARTICLES_PUBLISHED.filter(
    (a) => a.slug !== article.slug && a.modules.some((m) => article.modules.includes(m))
  ).slice(0, count)
}

